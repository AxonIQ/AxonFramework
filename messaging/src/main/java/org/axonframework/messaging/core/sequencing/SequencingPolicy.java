package org.axonframework.messaging.core.sequencing;

import org.axonframework.messaging.core.Message;
import org.axonframework.messaging.core.unitofwork.ProcessingContext;
import org.jspecify.annotations.Nullable;

import java.util.Optional;

/**
 * Interface to a policy definition for concurrent message processing.
 * <p/>
 * Some implementations are provided by default: <ul>
 * <li>{@link SequentialPolicy}: Requires that all messages are handled in the order they arrive. For event handling
 * this also means that at most 1 thread is processing messages for this processor at any time.</li>
 * <li>{@link FullConcurrencyPolicy}: Allows each message to be handled independently of any other message. Message
 * processing will typically start in the same order the messages were scheduled in, although no guarantees can be given
 * about the actual processing order.</li>
 * <li>{@link SequentialPerAggregatePolicy}: Will force events (only supports event handling tasks) generated by the
 * same aggregate to be handled sequentially. At most one thread will be processing events of a single aggregate at any
 * time. Resolves a sequence identifier only on event stores that publish an aggregate identifier alongside the event;
 * stores speaking the Dynamic Consistency Boundary protocol do not, and this policy resolves nothing there.</li>
 * <li>{@link RoutingKeySequencingPolicy}: Default command processing policy. Will force commands (only supports
 * command handling tasks) routed for the same routing key to be handled sequentially.</li>
 * <li>{@link ExtractionSequencingPolicy}: Message processing policy that allows to extract the sequence identifier
 * from the message payload.</li>
 * <li>{@link MetadataSequencingPolicy}: Message processing policy that allows to extract the sequence identifier from
 * the message metadata.</li>
 * <li>{@link PropertySequencingPolicy}: Message processing policy that extracts the sequence identifier from the
 * message payload based on a given property</li>
 * <li>{@link FallbackSequencingPolicy}: Message processing policy that allows two policies in an exception-based
 * fallback behavior for sequence identifier extraction.</li>
 * <li>{@link HierarchicalSequencingPolicy}: Message processing policy that allows to combine two policies in a
 * fallback pattern (similar to {@code FallbackSequencingPolicy}, but not exception based).</li>
 * </ul>
 * <p>
 * The default event processing policy is none of the above on its own. An event handling component that is given no
 * policy - see
 * {@link org.axonframework.messaging.eventhandling.SimpleEventHandlingComponent#create(String)
 * SimpleEventHandlingComponent.create(String)} - uses a {@link HierarchicalSequencingPolicy} of
 * {@link SequentialPerAggregatePolicy} with {@link SequentialPolicy} as its fallback. What that policy does depends on
 * the event store:
 * <ul>
 * <li>On an event store that publishes an aggregate identifier alongside the event, the primary half resolves that
 * identifier, so events of distinct aggregates are handled concurrently.</li>
 * <li>On an event store speaking the Dynamic Consistency Boundary protocol, no aggregate identifier is published, the
 * primary half resolves nothing, and the fallback answers for every event with a single constant identifier. Every
 * event in the stream therefore shares one sequence identifier. Two consequences follow. Events are handled strictly
 * one at a time. And because a
 * {@link org.axonframework.messaging.eventhandling.processing.streaming.segmenting.Segment} is selected by hashing the
 * sequence identifier, all events are routed to the single segment that constant identifier hashes into, leaving every
 * other configured segment with nothing to handle - so raising the segment or thread count buys no throughput.</li>
 * </ul>
 * Configure a policy that names your application's own ordering requirement to regain parallelism on such a store.
 *
 * @param <M> the type of message to sequence
 * @author Allard Buijze
 * @since 0.3
 */
@FunctionalInterface
public interface SequencingPolicy<M extends Message> {

    /**
     * Well-known sentinel sequence identifier signaling that a message should be handled by <b>every</b> handler
     * eligible for it, rather than being routed to a single one based on its sequence identifier.
     * <p>
     * When the sequence identifier resolved for a message equals {@code BROADCAST}, that message is
     * delivered to every eligible handler instead of only the one its identifier would otherwise select. Such messages
     * remain sequenced relative to one another wherever sequencing applies.
     * <p>
     * Note: This uses a String constant to provide consistent {@link Object#hashCode()} and
     * {@link Object#equals(Object)} behaviour across JVM restarts.
     *
     * @since 5.3.0
     */
    Object BROADCAST = "BROADCAST";

    /**
     * Returns the sequence identifier for the given {@code message}. When two messages have the same identifier (as
     * defined by their equals method), they will be executed sequentially. A {@code Optional#empty()} value indicates
     * that there are no sequencing requirements for the handling of this message.
     * <p>
     * The {@code Optional#empty()} should <b>only</b> be returned when the policy cannot determine a sequence
     * identifier for the given message. This typically happens when the policy is not applicable for the specific
     * message type. When {@code Optional#empty()} is returned, it is up to the component using this policy to provide a
     * default behavior, use another policy, throw an exception or react in any other way - as appropriate.
     *
     * @param message the message for which to get the sequencing identifier.
     * @param context the processing context in which the message is being handled. There might be limitations to the
     *                instance of the {@link ProcessingContext} depending on where the {@code SequencingPolicy} is being
     *                applied. When handling Events for example, the {@link ProcessingContext} doesn't allow you to
     *                register phases actions by for example {@link ProcessingContext#on} or retrieving components by
     *                {@link ProcessingContext#component}.
     * @return a sequence identifier for the given message, or {@code Optional#empty()} if this policy cannot determine
     * a sequence identifier for the given message.
     */
    Optional<Object> sequenceIdentifierFor(M message, @Nullable ProcessingContext context);
}
